    /// how the Shorts tab survived on the first Android run.
    #[test]
    fn mobile_youtube_rules_ship_in_the_desktop_window_css() {
        let css = page_css("https://www.youtube.com/", "youtube", false, &[]);
        assert!(
            css.contains("ytm-pivot-bar-item-renderer"),
            "m.youtube.com Shorts-tab rule must be in the injected CSS"
        );
        assert!(
            css.contains("ytm-reel-shelf-renderer"),
            "m.youtube.com Shorts-shelf rule must be in the injected CSS"
        );
    }

    /// Stage B (gaze-research.md): the generated runtime must actually be
    /// present in the binary and non-trivial — an empty or missing bundle
    /// would mean "smart" silently degrades to doing nothing.
    #[test]
    fn gaze_bundle_is_non_empty() {
        assert!(
            !GAZE_INIT_JS.is_empty(),
            "app/src-tauri/gaze-init.js is empty or missing — run `npm run build:gaze` in app/"
        );
    }

    /// The launcher's mode picker must actually change what gets
    /// injected — this is the wire between the "Smart" option and the
    /// page, same role as blur_toggle_reaches_the_injected_stylesheet
    /// plays for Stage A.
    #[test]
    fn smart_mode_injects_the_gaze_bundle_with_its_marker() {
        let script = gaze_script("smart");
        assert!(
            !script.is_empty(),
            "smart mode must inject a non-empty gaze script"
        );
        assert!(
            script.contains("__TS_GAZE_BUNDLE__"),
            "expected the gaze bundle's minification-proof marker in the \
             smart-mode injection — see gaze/src/init-entry.js"
        );
        assert!(
            script.contains("window.__TS_GAZE_MODE = \"smart\";"),
            "smart mode must set window.__TS_GAZE_MODE before the bundle runs"
        );
    }

    /// Compulsory tier (handoff decision #1): the bundle boots in every
    /// mode, with the NORMALISED mode baked in so the in-page plan
    /// (pipeline-plan.mjs) can gate what actually runs. Unrecognised
    /// modes must land on "off", never leak through as-is.
    #[test]
    fn gaze_injects_in_every_mode_with_normalised_mode_string() {
        for (mode, baked) in [("off", "off"), ("blur", "blur"), ("smart", "smart"), ("", "off"), ("bogus", "off")] {
            let script = gaze_script(mode);
            assert!(
                script.contains(&format!("window.__TS_GAZE_MODE = \"{baked}\";")),
                "mode {mode:?} must bake __TS_GAZE_MODE {baked:?}"
            );
            assert!(script.contains("__TS_GAZE_BUNDLE__"), "mode {mode:?} must carry the bundle");
        }
    }

    /// gaze_mode() must fall back to "off" for anything it doesn't
    /// recognise, never silently pass an unknown string through to the
    /// webview-building code.
    #[test]
    fn unknown_gaze_mode_falls_back_to_off() {
        assert_eq!(gaze_mode("smart"), "smart");
        assert_eq!(gaze_mode("blur"), "blur");
        assert_eq!(gaze_mode("off"), "off");
        assert_eq!(gaze_mode("nonsense"), "off");
        assert_eq!(gaze_mode(""), "off");
    }
