// Generates src/keywords-embed.mjs from the vendored dsojevic/profanity-list
// snapshot (vendor/profanity-en.json, MIT — see NOTICE). Same committed-
// generated-artifact treatment as model-embed.js. Scope: the protection
// engine's text signal wants sexualized-content terms, not a general
// profanity filter, so only `sexual`/`shock`-tagged entries ship
// (docs/keyword-research.md §5). Whole-word matching makes the upstream
// `exceptions` field (partial-match carve-outs) moot, so it is dropped.
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '../vendor/profanity-en.json');
const out = path.join(__dirname, '../src/keywords-embed.mjs');

// Hand-maintained algospeak supplement (docs/keyword-research.md §2):
// coined evasion words no license-clean list covers. Context-gated terms
// from the research ("corn", "accountant", "lebanese") are deliberately
// absent — too many innocent hits as standalone whole words.
const ALGOSPEAK = ['seggs', 'cornhub', 'corn hub', 'leg booty', 'legbooty'];

const list = JSON.parse(fs.readFileSync(src, 'utf8'));
const subset = list.filter(
  (e) => e.tags.includes('sexual') || e.tags.includes('shock')
);
const variants = new Set(ALGOSPEAK);
for (const e of subset) for (const v of e.match.split('|')) variants.add(v);

const body =
  '// GENERATED by build/gen-keywords.js — do not edit by hand.\n' +
  '// Source: vendor/profanity-en.json (dsojevic/profanity-list, MIT),\n' +
  '// filtered to sexual/shock tags, plus the algospeak supplement.\n' +
  'export const SEED_TERMS = ' +
  JSON.stringify([...variants].sort(), null, 0) +
  ';\n';
fs.writeFileSync(out, body);
console.log(`wrote ${out}: ${variants.size} terms from ${subset.length} entries`);
