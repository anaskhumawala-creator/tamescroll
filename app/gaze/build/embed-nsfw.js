// Reads the vendored nsfwjs MobileNetV2Mid model files
// (models/nsfw-mobilenet-v2-mid.{json,bin} — extracted from the nsfwjs npm
// package, MIT, see docs/gaze-research.md) and emits a JS module embedding
// the topology JSON + base64 weights, so the built bundle needs zero
// network/fetch at runtime. Same rationale as build/gen-embed.js: Reddit's
// CSP kills a runtime fetch outright, inlining is the only delivery path
// that works unconditionally on all three platforms.
//
// MobileNetV2Mid is a graph-model (options.type: "graph" in nsfwjs's own
// model registry) — same tfconv.loadGraphModel() + weightsManifest shape
// as BlazeFace, so it reuses detector.js's existing ioHandler pattern with
// zero new runtime dependencies. The plain "MobileNetV2" (small) model
// nsfwjs defaults to is a Keras LayersModel instead (needs
// @tensorflow/tfjs-layers, a different loader) — not used here.
const fs = require('fs');
const path = require('path');

const jsonPath = path.join(__dirname, '../models/nsfw-mobilenet-v2-mid.json');
const binPath = path.join(__dirname, '../models/nsfw-mobilenet-v2-mid.bin');

const json = fs.readFileSync(jsonPath, 'utf8');
const bin = fs.readFileSync(binPath);
const b64 = bin.toString('base64');

const out = `// AUTO-GENERATED by build/embed-nsfw.js — do not edit by hand.
export const NSFW_MODEL_JSON = ${json};
export const NSFW_WEIGHTS_B64 = ${JSON.stringify(b64)};
`;

const outPath = path.join(__dirname, '../src/nsfw-model-embed.js');
fs.writeFileSync(outPath, out);
console.log(
  `wrote ${outPath} (${(out.length / 1024 / 1024).toFixed(3)} MB source, b64 weights ${(b64.length / 1024 / 1024).toFixed(3)} MB)`
);
