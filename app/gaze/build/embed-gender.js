// Reads the vendored gender model (models/gender-ssrnet-imdb.{json,bin} —
// from vladmandic/human-models, MIT, see NOTICE; SSR-Net architecture) and
// emits a JS module embedding topology + base64 weights. Same zero-fetch
// rationale as embed-nsfw.js: Reddit's CSP kills runtime fetches, inlining
// is the only delivery that works on every platform. Graph model, so it
// reuses detector.js's embeddedIoHandler unchanged. Weights are tiny
// (~161KB — SSR-Net) so bundle impact is negligible.
const fs = require('fs');
const path = require('path');

const json = fs.readFileSync(path.join(__dirname, '../models/gender-ssrnet-imdb.json'), 'utf8');
const b64 = fs.readFileSync(path.join(__dirname, '../models/gender-ssrnet-imdb.bin')).toString('base64');

const out = `// AUTO-GENERATED by build/embed-gender.js — do not edit by hand.
export const GENDER_MODEL_JSON = ${json};
export const GENDER_WEIGHTS_B64 = ${JSON.stringify(b64)};
`;
const outPath = path.join(__dirname, '../src/gender-model-embed.js');
fs.writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${(out.length / 1024).toFixed(0)} KB source)`);
