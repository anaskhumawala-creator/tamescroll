// Reads the vendored gender model (models/gender-oarriaga.{json,bin} —
// human-models' gender.json, MIT, see NOTICE; Oarriaga mini-Xception,
// input 64x64x1 grayscale, output [female, male] softmax) and emits a JS
// module embedding topology + base64 weights. Replaced gender-ssrnet-imdb
// 2026-08-23: that file (verified byte-identical to upstream) outputs a
// SINGLE saturated value on real faces — constant ~1.0 under every
// documented preprocessing, i.e. unusable; upstream's own reader expects
// two outputs. Same zero-fetch rationale as embed-nsfw.js: Reddit's CSP
// kills runtime fetches, inlining is the only delivery that works on
// every platform. Weights are tiny (~202KB) so bundle impact is
// negligible.
const fs = require('fs');
const path = require('path');

const json = fs.readFileSync(path.join(__dirname, '../models/gender-oarriaga.json'), 'utf8');
const b64 = fs.readFileSync(path.join(__dirname, '../models/gender-oarriaga.bin')).toString('base64');

const out = `// AUTO-GENERATED by build/embed-gender.js — do not edit by hand.
export const GENDER_MODEL_JSON = ${json};
export const GENDER_WEIGHTS_B64 = ${JSON.stringify(b64)};
`;
const outPath = path.join(__dirname, '../src/gender-model-embed.js');
fs.writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${(out.length / 1024).toFixed(0)} KB source)`);
