// Reads the vendored gender model (models/faceres.{json,bin} —
// human-models' faceres.json, MIT, see NOTICE; HSE-FaceRes multi-head
// model returning age/gender/descriptor — we read only the gender head)
// and emits a JS module embedding topology + base64 weights.
//
// History: gender-ssrnet-imdb (broken upstream — single saturated output)
// -> gender-oarriaga mini-Xception 2026-08-23 (directionally correct on
// portraits but USELESS on real thumbnails: live calibration 2026-08-24
// scored true male faces 0.52-0.98 male with one misgendered outright,
// overlapping the wrong-gender band — no threshold separates that) ->
// faceres 2026-08-24 (7/7 direction-correct on the same live thumbnails
// in the browser spike, scratchpad gender-spike.html). Cost: ~7MB bin ->
// ~9.3MB base64 in the bundle. Same zero-fetch rationale as
// embed-nsfw.js: Reddit's CSP kills runtime fetches, inlining is the
// only delivery that works on every platform.
const fs = require('fs');
const path = require('path');

const json = fs.readFileSync(path.join(__dirname, '../models/faceres.json'), 'utf8');
const b64 = fs.readFileSync(path.join(__dirname, '../models/faceres.bin')).toString('base64');

const out = `// AUTO-GENERATED by build/embed-gender.js — do not edit by hand.
export const GENDER_MODEL_JSON = ${json};
export const GENDER_WEIGHTS_B64 = ${JSON.stringify(b64)};
`;
const outPath = path.join(__dirname, '../src/gender-model-embed.js');
fs.writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${(out.length / 1024 / 1024).toFixed(1)} MB source)`);
